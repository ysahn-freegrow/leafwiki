package auth

import (
	"context"
	"database/sql"
	"log"
	"path/filepath"
	"strings"
	"sync"
	"time"

	_ "modernc.org/sqlite"
)

// MCPTokenStore persists per-user MCP access tokens in its own SQLite file.
//
// Only a one-way SHA-256 hash of the token is stored, never the plaintext:
// unlike a web session, an MCP client presents the bare token on every request
// with no accompanying user id, so validation must locate the token by its
// value. That rules out a per-row salted hash (bcrypt), which cannot be looked
// up without first knowing the row. A deterministic SHA-256 over a 256-bit
// random token is the industry-standard choice (e.g. GitHub personal access
// tokens): it is one-way and not brute-forceable given the token's entropy,
// while still allowing an O(1) indexed lookup by hash.
//
// Exactly one token exists per user (enforced by a UNIQUE(user_id) index);
// regenerating replaces the previous row.
type MCPTokenStore struct {
	mu         sync.Mutex
	storageDir string
	filename   string
	db         *sql.DB
	cancel     context.CancelFunc
	done       chan struct{}
}

func mcpTokenDatabasePath(storageDir string, filename string) string {
	normalizedStorageDir := filepath.FromSlash(strings.ReplaceAll(storageDir, `\`, `/`))
	return filepath.Join(normalizedStorageDir, filename)
}

// NewMCPTokenStore opens (creating if needed) the mcp_tokens.db store and
// starts a background sweeper that deletes expired tokens hourly.
func NewMCPTokenStore(storageDir string) (*MCPTokenStore, error) {
	ctx, cancel := context.WithCancel(context.Background())
	s := &MCPTokenStore{
		storageDir: storageDir,
		filename:   "mcp_tokens.db",
		cancel:     cancel,
		done:       make(chan struct{}),
	}

	if err := s.ensureSchema(); err != nil {
		if s.db != nil {
			_ = s.db.Close()
			s.db = nil
		}
		cancel()
		return nil, err
	}

	go func() {
		defer close(s.done)
		ticker := time.NewTicker(1 * time.Hour)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				if err := s.CleanupExpiredTokens(); err != nil {
					log.Printf("failed to cleanup expired mcp tokens: %v", err)
				}
			}
		}
	}()

	return s, nil
}

func (s *MCPTokenStore) withDB(fn func(db *sql.DB) error) error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.db == nil {
		db, err := sql.Open("sqlite", mcpTokenDatabasePath(s.storageDir, s.filename))
		if err != nil {
			return err
		}
		s.db = db
	}

	return fn(s.db)
}

func (s *MCPTokenStore) ensureSchema() error {
	return s.withDB(func(db *sql.DB) error {
		_, err := db.Exec(`
			CREATE TABLE IF NOT EXISTS mcp_tokens (
				id TEXT PRIMARY KEY,
				user_id TEXT NOT NULL UNIQUE,   -- one active MCP token per user
				token_hash TEXT NOT NULL UNIQUE, -- sha256 hex of the plaintext token
				created_at INTEGER NOT NULL,    -- unix sec
				expires_at INTEGER NOT NULL,    -- unix sec, created_at + fixed lifetime
				last_used_at INTEGER            -- unix sec, NULL until first successful use
			);

			CREATE INDEX IF NOT EXISTS mcp_tokens_token_hash_idx
				ON mcp_tokens(token_hash);
		`)
		return err
	})
}

func (s *MCPTokenStore) Close() error {
	s.cancel()
	<-s.done
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.db != nil {
		if err := s.db.Close(); err != nil {
			return err
		}
		s.db = nil
	}
	return nil
}

// Upsert replaces any existing token for userID with the given token, so that
// regenerating invalidates the previous one. id/tokenHash must be freshly
// generated by the caller.
func (s *MCPTokenStore) Upsert(id, userID, tokenHash string, createdAt, expiresAt time.Time) error {
	return s.withDB(func(db *sql.DB) error {
		tx, err := db.Begin()
		if err != nil {
			return err
		}
		defer func() { _ = tx.Rollback() }()

		if _, err := tx.Exec(`DELETE FROM mcp_tokens WHERE user_id = ?;`, userID); err != nil {
			return err
		}
		if _, err := tx.Exec(`
			INSERT INTO mcp_tokens (id, user_id, token_hash, created_at, expires_at, last_used_at)
			VALUES (?, ?, ?, ?, ?, NULL);
		`, id, userID, tokenHash, createdAt.Unix(), expiresAt.Unix()); err != nil {
			return err
		}
		return tx.Commit()
	})
}

// GetByHash returns the token record whose hash matches, or (nil, nil) when no
// such token exists. It does not filter on expiry/last_used; callers decide
// what an expired token means.
func (s *MCPTokenStore) GetByHash(tokenHash string) (*MCPToken, error) {
	return s.getBy("token_hash", tokenHash)
}

// GetByUser returns the (single) token record for userID, or (nil, nil) when
// the user has no MCP token.
func (s *MCPTokenStore) GetByUser(userID string) (*MCPToken, error) {
	return s.getBy("user_id", userID)
}

func (s *MCPTokenStore) getBy(column, value string) (*MCPToken, error) {
	var (
		tok        MCPToken
		createdAt  int64
		expiresAt  int64
		lastUsedAt sql.NullInt64
	)
	err := s.withDB(func(db *sql.DB) error {
		return db.QueryRow(`
			SELECT id, user_id, created_at, expires_at, last_used_at
			FROM mcp_tokens
			WHERE `+column+` = ?;
		`, value).Scan(&tok.ID, &tok.UserID, &createdAt, &expiresAt, &lastUsedAt)
	})
	if err == sql.ErrNoRows {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	tok.CreatedAt = time.Unix(createdAt, 0)
	tok.ExpiresAt = time.Unix(expiresAt, 0)
	if lastUsedAt.Valid {
		t := time.Unix(lastUsedAt.Int64, 0)
		tok.LastUsedAt = &t
	}
	return &tok, nil
}

// TouchLastUsed records that the token identified by id was used at the given
// time. A failure here must never block the request that triggered it, so
// callers typically log and continue.
func (s *MCPTokenStore) TouchLastUsed(id string, at time.Time) error {
	return s.withDB(func(db *sql.DB) error {
		_, err := db.Exec(`
			UPDATE mcp_tokens SET last_used_at = ? WHERE id = ?;
		`, at.Unix(), id)
		return err
	})
}

// DeleteForUser removes the user's MCP token, immediately revoking it. It is a
// no-op if the user has no token.
func (s *MCPTokenStore) DeleteForUser(userID string) error {
	return s.withDB(func(db *sql.DB) error {
		_, err := db.Exec(`DELETE FROM mcp_tokens WHERE user_id = ?;`, userID)
		return err
	})
}

// CleanupExpiredTokens deletes tokens whose expiry has passed. Expired tokens
// are already rejected at validation time; this just keeps the table small.
func (s *MCPTokenStore) CleanupExpiredTokens() error {
	now := time.Now()
	return s.withDB(func(db *sql.DB) error {
		_, err := db.Exec(`DELETE FROM mcp_tokens WHERE expires_at <= ?;`, now.Unix())
		return err
	})
}
